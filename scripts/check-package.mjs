import assert from 'node:assert/strict';
import {readFile} from 'node:fs/promises';
import {spawnSync} from 'node:child_process';
import {createRequire} from 'node:module';
import {runInNewContext} from 'node:vm';
import {fileURLToPath} from 'node:url';
const root=fileURLToPath(new URL('../',import.meta.url));
const manifest=JSON.parse(await readFile(new URL('../package.json',import.meta.url),'utf8'));
for(const key of ['prepare','prepack','preinstall','install','postinstall'])assert.equal(manifest.scripts?.[key],undefined);
assert.ok(process.env.npm_execpath,'Run with npm run check:package');
const result=spawnSync(process.execPath,[process.env.npm_execpath,'pack','--dry-run','--ignore-scripts','--json'],{cwd:root,encoding:'utf8'});
assert.equal(result.status,0,result.stderr);
const files=JSON.parse(result.stdout)[0].files.map(file=>file.path);
for(const entry of [manifest.main,...Object.values(manifest.exports),manifest.dsh.bundle.patch,'THIRD_PARTY_NOTICES.md'])assert.ok(files.includes(entry.replace(/^\.\//,'')),entry);
assert.ok(!files.some(path=>/^(editors|scripts|test|node_modules)\/|\.map$/.test(path)));
let client;runInNewContext(await readFile(new URL('../lib/client.js',import.meta.url),'utf8'),{window:{__ModuleLoader__:{load:value=>{client=value;}}}});
assert.equal(client.id,manifest.name);assert.equal(typeof client.factory(createRequire(import.meta.url)).apply,'function');
assert.equal(typeof (await import('../lib/index.js')).apply,'function');
assert.equal((await import('../lib/remote.js')).TYPERT.package,manifest.name);
console.log(`Installable ${manifest.name}@${manifest.version}: ${files.length} files; three bundle entries verified.`);
